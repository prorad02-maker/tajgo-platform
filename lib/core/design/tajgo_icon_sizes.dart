/// TajGo icon size scale.
class TajGoIconSizes {
  const TajGoIconSizes._();

  /// 16 px — inline-иконки в тексте/чипах.
  static const double sm = 16;

  /// 20 px — иконки в полях и строках списка.
  static const double md = 20;

  /// 24 px — стандартные иконки навигации/действий.
  static const double lg = 24;

  /// 32 px — акцентные иконки категорий.
  static const double xl = 32;

  /// 48 px — крупные иконки empty/error состояний.
  static const double hero = 48;
}
